const DICTS: Record<Lang, Strings> = { en, ar, fr };

export type StringKey = keyof Strings;

/** Resolves the interface language: the setting, or the browser language when set to "auto". */
export function resolveUiLanguage(setting: UiLanguage, browserLang: string = navigator.language): Lang {
  if (setting !== 'auto') return setting;
  const l = browserLang.toLowerCase();
  if (l.startsWith('ar')) return 'ar';
  if (l.startsWith('fr')) return 'fr';
  return 'en';
}

export function makeT(lang: Lang) {
  const dict = DICTS[lang];
  return (key: StringKey, vars?: Record<string, string | number>): string => {
    let s: string = dict[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export type T = ReturnType<typeof makeT>;

export const dirOf = (lang: Lang): 'rtl' | 'ltr' => (lang === 'ar' ? 'rtl' : 'ltr');
